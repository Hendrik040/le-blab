import AppKit

/// Full copy of a pasteboard's items (every type of every item), so a paste-based insertion
/// can put the user's clipboard back exactly as it was.
public struct PasteboardSnapshot {
    public let items: [[NSPasteboard.PasteboardType: Data]]

    public init(of pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    public var isEmpty: Bool { items.isEmpty }

    public func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}

public enum PasteboardMarkers {
    /// nspasteboard.org conventions: clipboard managers (Maccy, Raycast, Alfred, Paste…) skip these,
    /// so dictated text placed on the clipboard for a paste never lands in clipboard history.
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// Writes `text` as a transient item. Returns the resulting change count.
    @discardableResult
    public static func writeTransient(_ text: String, to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transient)
        item.setData(Data(), forType: concealed)
        item.setData(Data(), forType: autoGenerated)
        item.setString("local.leblab.LeBlab", forType: source)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
}
